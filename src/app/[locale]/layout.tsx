import { NextIntlClientProvider } from 'next-intl'
import { getTranslations, setRequestLocale } from 'next-intl/server'
import { hasLocale } from 'next-intl'
import { notFound } from 'next/navigation'
import type { Metadata } from 'next'
import type { ReactNode } from 'react'

import { Menu } from '@/components/layout/Menu'
import { TransitionOverlay } from '@/components/layout/TransitionOverlay'
import { site } from '@/config/site.config'
import { pathFor } from '@/i18n/paths'
import { routing } from '@/i18n/routing'
import { MenuProvider } from '@/lib/menu'
import { resolveCanonicalUrl } from '@/lib/config/resolve'

import '@/styles/globals.css'

/* ══════════════════════════════════════════════════════════════════════════════
   ROOT LAYOUT FOR EVERY LOCALIZED PAGE

   A root layout under a dynamic segment, which Next 16 documents explicitly for this case
   (`layout.md`: "The root layout can be under a dynamic segment, for example when implementing
   internationalization with `app/[lang]/layout.js`"). That is what lets `<html lang>` be the
   locale from the URL.

   ── This is where the persistent chrome mounts ─────────────────────────────────
   The menu and the page-transition overlay mount here — and
   nowhere else: the `MenuProvider` owns the state, the panel renders after
   `<main>`, and the overlay joins beside it, still inside the provider (its
   imperative entry is the sequence owner's seam, and the sequence owner reads
   `useMenu()`). There is deliberately **no `template.tsx`** in this tree: that
   convention remounts on every navigation, so the router unmounts the outgoing tree
   immediately and `AnimatePresence` never gets to hold it. This layout is not
   remounted across navigation, so the animation context survives and both halves of a
   transition run.
   ══════════════════════════════════════════════════════════════════════════════ */

/* The document metadata, from the central configuration (replacing the
   original placeholder). The layout carries the site-wide set: the title —
   the site's own line, so a page without a title shows it — the default
   description, the landing's canonical, and the
   OpenGraph set, whose image is the Works image (`seo.ogImage`). Pages
   override title/description/canonical for their own document (the legal
   page does) and inherit the OG set; `scripts/check-metadata.ts` stays a
   stub until its assertions are implemented. */
export async function generateMetadata({
  params,
}: {
  params: Promise<{ locale: string }>
}): Promise<Metadata> {
  const { locale } = await params

  const title = site.seo.title
  const canonical = resolveCanonicalUrl(pathFor({ href: '/', locale }))
  const ogImage = resolveCanonicalUrl(site.seo.ogImage)

  return {
    title,
    description: site.seo.defaultDescription,
    alternates: { canonical },
    openGraph: {
      title,
      description: site.seo.defaultDescription,
      url: canonical,
      siteName: site.identity.displayName,
      type: 'website',
      locale,
      images: [{ url: ogImage }],
    },
    /* The favicon set is the minimal one: the SVG mark —
       a square version of `logo.svg` — plus the one iOS home-screen icon,
       generated by `scripts/build-favicons.ts` and committed with the PNG. */
    icons: { icon: '/tab-icon.svg', apple: '/apple-touch-icon.png' },
  }
}

/**
 * Every configured locale, so the export contains a complete document tree for each.
 * A locale never generated simply does not exist in the output — the export is
 * silently incomplete rather than loudly broken.
 */
export function generateStaticParams() {
  return routing.locales.map((locale) => ({ locale }))
}

export default async function LocaleLayout({
  children,
  params,
}: {
  children: ReactNode
  params: Promise<{ locale: string }>
}) {
  const { locale } = await params

  /* The `[locale]` segment acts as a catch-all for unknown top-level paths, so an
     unrecognised value reaches the not-found document rather than rendering an empty shell
     in a locale that does not exist. */
  if (!hasLocale(routing.locales, locale)) notFound()

  /* Opts this subtree into static rendering. Without it next-intl treats the request as
     dynamic, which a static export cannot satisfy. */
  setRequestLocale(locale)

  const t = await getTranslations({ locale })

  return (
    <html lang={locale}>
      <body>
        <NextIntlClientProvider locale={locale}>
          <MenuProvider>
            <a className="skip-link" href="#main-content">
              {t('common.skipToContent')}
            </a>
            {/* One `<main>` per document, so the skip link's target is unambiguous. */}
            <main id="main-content">{children}</main>
            {/* The menu panel: after `<main>`, in the persistent layout, so its
                exit animations can run (no `template.tsx`). */}
            <Menu />
            {/* The page-transition overlay: beside the menu, in the
                same persistent layout, so the cover and the reveal can run
                (no `template.tsx`). */}
            <TransitionOverlay />
          </MenuProvider>
        </NextIntlClientProvider>
      </body>
    </html>
  )
}
